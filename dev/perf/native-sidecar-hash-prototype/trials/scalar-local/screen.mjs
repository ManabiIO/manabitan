import assert from 'node:assert/strict'
import {createHash} from 'node:crypto'
import {readFile, writeFile} from 'node:fs/promises'
import {dirname, join, resolve} from 'node:path'
import {fileURLToPath} from 'node:url'
import {createNativeChecksum} from './native-checksum.mjs'
import {hashTermKeyBytes} from '../../../ext/js/dictionary/term-key-hash.js'

const [inputDirectory, outputPath, roundsArg = '7', repeatsArg = '256'] = process.argv.slice(2)
assert(inputDirectory && outputPath)
const rounds = Number(roundsArg)
const repeats = Number(repeatsArg)
assert(Number.isInteger(rounds) && rounds > 0 && rounds <= 101)
assert(Number.isInteger(repeats) && repeats > 0 && repeats <= 4096)
const directory = dirname(fileURLToPath(import.meta.url))
const root = resolve(directory, '../../..')
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex')
const manifestBytes = await readFile(join(inputDirectory, 'manifest.json'))
const manifest = JSON.parse(manifestBytes)
const firstInput = manifest.dictionaries[0].inputs[0]
const firstBytes = new Uint8Array(await readFile(join(inputDirectory, firstInput.filename)))
assert.equal(sha256(firstBytes), firstInput.sha256)
const wasm = await readFile(join(directory, 'xxh32-stream.wasm'))
const initializedAt = performance.now()
const native = await createNativeChecksum(wasm)
const initializationMs = performance.now() - initializedAt
const firstNativeStartedAt = performance.now()
const firstNativeResult = native.hashBytes(firstBytes)
const firstNativeHashMs = performance.now() - firstNativeStartedAt
const firstJsStartedAt = performance.now()
const firstJsResult = hashTermKeyBytes(firstBytes)
const firstJsHashMs = performance.now() - firstJsStartedAt
assert.equal(firstNativeResult, firstInput.xxh32)
assert.equal(firstJsResult, firstInput.xxh32)

// Existing test vectors are fixed values generated by upstream XXH32, rather
// than expected values computed from either implementation under comparison.
const fixedVectorSource = await readFile(join(root, 'test/term-key-hash.test.js'), 'utf8')
const vectors = [...fixedVectorSource.slice(0, fixedVectorSource.indexOf('function makePayload'))
    .matchAll(/\[(\d+), (\d+)\]/g)].map((match) => [Number(match[1]), Number(match[2])])
assert(vectors.length >= 150)
for (const [length, expected] of vectors) {
    const payload = Uint8Array.from({length}, (_, i) => ((i * 131) ^ ((i >>> 7) * 17) ^ length) & 0xff)
    assert.equal(native.hashBytes(payload), expected)
    for (const shift of [1, 3, 7]) {
        const shifted = new Uint8Array(length + shift + 11)
        shifted.set(payload, shift)
        assert.equal(native.hashByteRange(shifted, shift, shift + length), expected)
    }
}

const results = []
const median = (values) => values.toSorted((a, b) => a - b)[Math.floor(values.length / 2)]
let sink = 0
let randomState = 0xbeb52026
const reverseOrder = () => {
    randomState ^= randomState << 13
    randomState ^= randomState >>> 17
    randomState ^= randomState << 5
    return (randomState & 1) !== 0
}
for (const item of manifest.dictionaries) {
    const inputs = []
    for (const input of item.inputs) {
        const file = await readFile(join(inputDirectory, input.filename))
        assert.equal(file.byteLength, input.bytes)
        assert.equal(sha256(file), input.sha256)
        const bytes = new Uint8Array(file)
        assert.equal(hashTermKeyBytes(bytes), input.xxh32)
        assert.equal(native.hashBytes(bytes), input.xxh32)
        inputs.push(bytes)
    }
    const run = (hash, count) => {
        const startedAt = performance.now()
        for (let i = 0; i < count; i++) {
            for (const bytes of inputs) sink ^= hash(bytes)
        }
        return performance.now() - startedAt
    }
    for (let i = 0; i < 3; i++) {
        run(hashTermKeyBytes, 32)
        run(native.hashBytes, 32)
    }
    const samples = []
    const controls = []
    for (let round = 0; round < rounds; round++) {
        const order = reverseOrder() ? ['js', 'native', 'native', 'js'] : ['native', 'js', 'js', 'native']
        const sample = {round, order, js: [], native: []}
        for (const arm of order) sample[arm].push(run(arm === 'js' ? hashTermKeyBytes : native.hashBytes, repeats))
        sample.jsMs = (sample.js[0] + sample.js[1]) / 2
        sample.nativeMs = (sample.native[0] + sample.native[1]) / 2
        sample.nativeOverJs = sample.nativeMs / sample.jsMs
        samples.push(sample)
        const control = {round, order: reverseOrder() ? ['a', 'b', 'b', 'a'] : ['b', 'a', 'a', 'b'], a: [], b: []}
        for (const arm of control.order) control[arm].push(run(hashTermKeyBytes, repeats))
        control.bOverA = (control.b[0] + control.b[1]) / (control.a[0] + control.a[1])
        controls.push(control)
    }
    const result = {
        dictionary: item.dictionary, bank: item.bank, bankSha256: item.bankSha256, rows: item.rows,
        inputBytes: inputs.reduce((sum, input) => sum + input.byteLength, 0),
        inputs: item.inputs, rounds, repeats, samples, controls,
        medianJsMs: median(samples.map((sample) => sample.jsMs)),
        medianNativeMs: median(samples.map((sample) => sample.nativeMs)),
        medianPairedRatio: median(samples.map((sample) => sample.nativeOverJs)),
        medianControlRatio: median(controls.map((sample) => sample.bOverA)),
    }
    results.push(result)
    console.log(JSON.stringify(result))
}
const report = {
    scope: 'Node first-bank checksum kernel screening; includes guarded input admission, bounded copies and WASM calls; not whole-import qualification',
    node: process.version, platform: process.platform, architecture: process.arch,
    wasmSha256: sha256(wasm), inputManifestSha256: sha256(manifestBytes),
    wrapperSha256: sha256(await readFile(join(directory, 'native-checksum.mjs'))),
    baselineHashSourceSha256: sha256(await readFile(join(root, 'ext/js/dictionary/term-key-hash.js'))),
    harnessSha256: sha256(await readFile(fileURLToPath(import.meta.url))),
    initializationMs, firstNativeHashMs, firstJsHashMs,
    firstHashBytes: firstBytes.byteLength, firstHashOrder: ['native', 'js'],
    firstHashScope: 'One fresh Node process diagnostic, not a paired cold-start estimate',
    randomSeed: '0xbeb52026', memoryBytes: native.memoryBytes, scratchBytes: native.scratchBytes,
    fixedVectorCount: vectors.length, checkedRanges: vectors.length * 4, sink, results,
}
await writeFile(outputPath, JSON.stringify(report, null, 2) + '\n', {flag: 'wx'})
