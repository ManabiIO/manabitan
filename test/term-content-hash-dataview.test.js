/**
 * @param {number} size
 * @param {number} pattern
 * @returns {Uint8Array<ArrayBuffer>}
 */
function createInput(size, pattern) {
    return Uint8Array.from({length: size}, (_, index) => {
        if (pattern === 0) { return ((index * 73) ^ (index >>> 8)) & 255; }
        return [0, 0, 255, 128][pattern];
    });
}

test('content hashes match independent native XXH32 vectors at every alignment', () => {
    for (const [size, pattern, h1, h2] of vectors) {
        const input = createInput(size, pattern);
        for (const offset of [0, 1, 7]) {
            const backing = new Uint8Array(size + offset + 9).fill(177);
            backing.set(input, offset);
            const bytes = backing.subarray(offset, offset + size);
            const before = Uint8Array.from(backing);
            assert.deepEqual(hashTermEntryContentBytesPair(bytes), [h1, h2], `${size}/${pattern}/${offset}`);
            assert.equal(hashTermEntryContentBytes(bytes), h1.toString(16).padStart(8, '0') + h2.toString(16).padStart(8, '0'));
            assert.deepEqual(backing, before);
        }
    }
});

test('large Buffer slices hash only their selected bytes', () => {
    for (const [size, pattern, h1, h2] of vectors) {
        if (size < 256) { continue; }
        const input = createInput(size, pattern);
        const backing = Buffer.alloc(size + 19, 177);
        backing.set(input, 3);
        assert.deepEqual(hashTermEntryContentBytesPair(backing.subarray(3, 3 + size)), [h1, h2]);
    }
});

test('shared views preserve the exact hash pair', () => {
    const vector = vectors.find(([size, pattern]) => size === 4096 && pattern === 0);
    assert.ok(vector);
    const [size, pattern, h1, h2] = vector;
    const bytes = new Uint8Array(new SharedArrayBuffer(size + 17), 5, size);
    bytes.set(createInput(size, pattern));
    assert.deepEqual(hashTermEntryContentBytesPair(bytes), [h1, h2]);
});

test('empty detached views retain empty-input behavior', () => {
    const bytes = createInput(4096, 0);
    structuredClone(bytes.buffer, {transfer: [bytes.buffer]});
    assert.equal(bytes.byteLength, 0);
    assert.deepEqual(hashTermEntryContentBytesPair(bytes), hashTermEntryContentBytesPair(new Uint8Array(0)));
});

test('block envelopes preserve persisted checksums and payload ownership', () => {
    for (const [size, pattern, h1, h2] of vectors) {
        if (size === 0) { continue; }
        const input = createInput(size, pattern);
        const output = wrapCompressedTermContentBlock(input);
        assert.equal(output.length, input.length + 12);
        assert.deepEqual(output.subarray(0, 4), new Uint8Array([0x4d, 0x42, 0x43, 0x32]));
        const view = new DataView(output.buffer, output.byteOffset, output.byteLength);
        assert.equal(view.getUint32(4, true), h1);
        assert.equal(view.getUint32(8, true), h2);
        assert.deepEqual(output.subarray(12), input);
        assert.notEqual(output.buffer, input.buffer);
        output[12] ^= 255;
        assert.deepEqual(input, createInput(size, pattern));
    }
});
