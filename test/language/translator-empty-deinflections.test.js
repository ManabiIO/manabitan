import {expect, test} from 'vitest';
import {Translator} from '../../ext/js/language/translator.js';

const dictionary = 'Deinflection batch fixture';

/**
 * @param {Map<string, import('dictionary-database').TermEntry[]>} entriesByTerm
 * @returns {{translator: Translator, calls: string[][]}}
 */
function createTranslator(entriesByTerm) {
    /** @type {string[][]} */
    const calls = [];
    const database = /** @type {{findTermsBulk: (terms: string[]) => Promise<import('dictionary-database').TermEntry[]>}} */ (/** @type {unknown} */ ({
        /**
         * @param {string[]} terms
         * @returns {Promise<import('dictionary-database').TermEntry[]>}
         */
        async findTermsBulk(terms) {
            calls.push([...terms]);
            return terms.flatMap((term, index) => (entriesByTerm.get(term) ?? []).map((entry) => ({...entry, index})));
        },
    }));
    const translator = new Translator(/** @type {ConstructorParameters<typeof Translator>[0]} */ (/** @type {unknown} */ (database)));
    translator.prepare();
    return {translator, calls};
}

/** @returns {import('translation').FindTermsOptions} */
function createOptions() {
    return {
        matchType: 'exact',
        deinflect: false,
        mainDictionary: dictionary,
        sortFrequencyDictionary: null,
        sortFrequencyDictionaryOrder: 'descending',
        removeNonJapaneseCharacters: false,
        primaryReading: '',
        textReplacements: [null],
        enabledDictionaryMap: new Map([[dictionary, {
            index: 0,
            alias: dictionary,
            allowSecondarySearches: false,
            partsOfSpeechFilter: false,
            useDeinflections: true,
        }]]),
        excludeDictionaryDefinitions: null,
        searchResolution: 'word',
        language: 'en',
        useAllFrequencyDictionaries: false,
    };
}

/**
 * @param {string} term
 * @param {import('dictionary-data').TermGlossary[]} definitions
 * @returns {import('dictionary-database').TermEntry}
 */
function createEntry(term, definitions) {
    return {
        index: 0,
        matchType: 'exact',
        matchSource: 'term',
        term,
        reading: '',
        definitionTags: [],
        termTags: [],
        rules: [],
        definitions,
        score: 1,
        dictionary,
        id: 1,
        sequence: -1,
    };
}

test('does not query the database for an empty dictionary-defined inflection batch', async () => {
    const {translator, calls} = createTranslator(new Map());

    const result = await translator.findTerms('simple', 'ordinary', createOptions());

    expect(result.dictionaryEntries).toEqual([]);
    expect(calls).toEqual([['ordinary']]);
});

test('still queries a form-of entry generated by dictionary definitions', async () => {
    const formOfEntry = createEntry('surface', [
        ['lemma', ['form-of']],
    ]);
    const {translator, calls} = createTranslator(new Map([
        ['surface', [formOfEntry]],
        ['lemma', [createEntry('lemma', ['lemma definition'])]],
    ]));

    const result = await translator.findTerms('simple', 'surface', createOptions());

    expect(calls).toEqual([['surface'], ['lemma']]);
    expect(result.dictionaryEntries.map(({headwords}) => headwords[0].term)).toContain('lemma');
});
