/**
 * @param {number} length
 * @returns {Uint8Array}
 */
function makePayload(length) {
    return Uint8Array.from({length}, (_, i) => ((i * 131) ^ ((i >>> 7) * 17) ^ length) & 0xff);
}

describe('stable term lookup key and integrity hashes', () => {
    test.each(VECTORS)('matches upstream XXH32 at %i bytes', (length, expected) => {
        const payload = makePayload(length);
        expect(hashTermKeyBytes(payload)).toBe(expected);
        for (const shared of [false, true]) {
            for (const byteOffset of [0, 1, 3, 7]) {
                for (const start of [0, 1, 5]) {
                    const byteLength = byteOffset + start + length + 13;
                    const backing = shared ? new SharedArrayBuffer(byteLength) : new ArrayBuffer(byteLength);
                    const view = new Uint8Array(backing, byteOffset);
                    view.fill(0xa5);
                    view.set(payload, start);
                    expect(hashTermKeyByteRange(view, start, start + length)).toBe(expected);
                    const exact = view.subarray(start, start + length);
                    expect(hashTermKeyBytes(exact)).toBe(expected);
                }
            }
        }
    });
});
